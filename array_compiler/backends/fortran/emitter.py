                first_type = self._expr_type(expr.args[0]) if expr.args else None
                if isinstance(first_type, ArrayTypeRef) and expr.func in {"abs", "sqrt", "exp", "log"}:
                    return ArrayTypeRef(ScalarType.REAL64, rank=first_type.rank)
